    /** En yakın il merkezinin sırası ve uzaklığı (km). */
    static int nearest(double lat, double lon, double[] distanceKmOut) {
        int best = 0;
        double bestD = Double.MAX_VALUE;
        for (int i = 0; i < NAMES.length; i++) {
            double d = distanceKm(lat, lon, LAT[i], LON[i]);
            if (d < bestD) { bestD = d; best = i; }
        }
        if (distanceKmOut != null && distanceKmOut.length > 0) distanceKmOut[0] = bestD;
        return best;
    }

    static int indexOf(String name) {
        for (int i = 0; i < NAMES.length; i++) if (NAMES[i].equals(name)) return i;
        return -1;
    }

    static double distanceKm(double lat1, double lon1, double lat2, double lon2) {
        double r = 6371.0;
        double dLat = Math.toRadians(lat2 - lat1);
        double dLon = Math.toRadians(lon2 - lon1);
        double a = Math.sin(dLat / 2) * Math.sin(dLat / 2)
                + Math.cos(Math.toRadians(lat1)) * Math.cos(Math.toRadians(lat2))
                * Math.sin(dLon / 2) * Math.sin(dLon / 2);
        return 2 * r * Math.asin(Math.min(1.0, Math.sqrt(a)));
    }
